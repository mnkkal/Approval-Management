-- Schema Migration 004: Feedback Threads, Pinned Comments & Tamper-Evident Sign-Offs
-- ==============================================================================

-- 1. Feedback Threads (Coordinate pins, PDF pages, Video timestamps)
CREATE TABLE feedback_threads (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    version_id UUID NOT NULL REFERENCES deliverable_versions(id) ON DELETE CASCADE,
    is_internal BOOLEAN NOT NULL DEFAULT FALSE, -- Crucial: agency internal notes vs client visible
    status VARCHAR(32) NOT NULL DEFAULT 'open', -- open, resolved
    
    -- Positioning data
    coordinates JSONB, -- {"x": 42.5, "y": 68.2, "width": null, "height": null}
    page_number INT, -- For multi-page PDFs
    timestamp_seconds NUMERIC(8, 3), -- Frame-accurate for video (e.g., 84.250s)
    
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP WITH TIME ZONE,
    resolved_by_email VARCHAR(255)
);

CREATE INDEX idx_threads_version_internal ON feedback_threads(version_id, is_internal);

-- 2. Comments within Threads
CREATE TABLE comments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    thread_id UUID NOT NULL REFERENCES feedback_threads(id) ON DELETE CASCADE,
    author_type VARCHAR(16) NOT NULL, -- 'user' or 'guest'
    author_user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    author_email VARCHAR(255) NOT NULL,
    author_name VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    attachments JSONB DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_comments_thread ON comments(thread_id, created_at);

-- 3. Explicit Approval Ledger
CREATE TABLE approvals (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    version_id UUID NOT NULL REFERENCES deliverable_versions(id) ON DELETE RESTRICT,
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    deliverable_id UUID NOT NULL REFERENCES deliverables(id) ON DELETE CASCADE,
    version_number INT NOT NULL,
    asset_sha256 CHAR(64) NOT NULL,
    
    -- Approver Identity (Verified via Email OTP or registered user account)
    approver_email VARCHAR(255) NOT NULL,
    approver_name VARCHAR(255) NOT NULL,
    verification_method VARCHAR(32) NOT NULL, -- 'email_otp' or 'authenticated_user'
    
    -- Legal Confirmation & Evidence Trail
    confirmation_statement_text TEXT NOT NULL,
    client_fingerprint JSONB NOT NULL, -- {ip_hash, user_agent, locale, screen_resolution}
    previous_event_hash VARCHAR(64), -- Forward-hash chain for tamper evidence
    record_signature VARCHAR(128) NOT NULL, -- HMAC-SHA256 signature generated by server secret
    
    approved_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_approvals_version ON approvals(version_id);
CREATE INDEX idx_approvals_deliverable ON approvals(deliverable_id);

-- 4. Audit Log (Append-only security log)
CREATE TABLE audit_logs (
    id BIGSERIAL PRIMARY KEY,
    workspace_id UUID NOT NULL,
    event_type VARCHAR(64) NOT NULL, -- 'otp.sent', 'otp.verified', 'deliverable.created', 'approval.executed', 'approval.revoked'
    actor_email VARCHAR(255) NOT NULL,
    ip_address_hash CHAR(64) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id UUID NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_workspace_event ON audit_logs(workspace_id, event_type);
